import {createInvitationAcceptor} from './invitation-acceptance-repository.ts';
import {createInvitationReader} from './invitation-reader.ts';
import {createInvitationWriter,createInvitationRevoker} from './invitation-repository.ts';
import {createPermissionReader} from './permission-repository.ts';
import {createLearningExporter} from './export-repository.ts';
import {createApp} from './app.ts';
import pg from 'pg';
import {createProfileReader} from './profile-repository.ts';
import {createFamilyWriter} from './family-repository.ts';
import {createJwtIdentityVerifier} from './identity.ts';
import {createIdentityLookup,createIdentityRegistrar} from './identity-repository.ts';
import {createProfileDeletionWriter,createDeletionReader} from './deletion-repository.ts';
import {createProgressReader} from './progress-repository.ts';
import {createMemberWriter} from './member-repository.ts';
import {createSessionRepository} from './session-repository.ts';
import {createBrowserIdentityVerifier} from './browser-session.ts';
import {createRecognitionSubmitter} from './english-assessment.ts';
import {createAttemptWriter} from './attempt-repository.ts';
import {createSettingsRepository} from './settings-repository.ts';
const port=Number(process.env.PORT??8787);
if(!Number.isInteger(port)||port<1||port>65535)throw new Error('INVALID_PORT');
const pool=process.env.DATABASE_URL?new pg.Pool({connectionString:process.env.DATABASE_URL,max:4,connectionTimeoutMillis:5000,idleTimeoutMillis:30000}):undefined;
pool?.on('error',()=>console.error('DATABASE_POOL_ERROR'));
const identityValues=[process.env.AUTH_ISSUER,process.env.AUTH_AUDIENCE,process.env.AUTH_JWKS_URL];
if(identityValues.some(Boolean)&&(!pool||!identityValues.every(Boolean)))throw new Error('INCOMPLETE_IDENTITY_CONFIGURATION');
const identityConfig={issuer:identityValues[0]!,audience:identityValues[1]!,jwksUrl:identityValues[2]!};
const verifyBearer=pool&&identityValues.every(Boolean)?createJwtIdentityVerifier(identityConfig,createIdentityLookup(pool)):undefined;
if(process.env.AUTH_ALLOW_SIGNUP&&!['true','false'].includes(process.env.AUTH_ALLOW_SIGNUP))throw new Error('INVALID_SIGNUP_CONFIGURATION');
const verifyProof=pool&&verifyBearer&&process.env.AUTH_ALLOW_SIGNUP==='true'?createJwtIdentityVerifier(identityConfig,createIdentityRegistrar(pool)):verifyBearer;
const origin=process.env.PUBLIC_ORIGIN??'http://127.0.0.1:5173';
const secure=new URL(origin).protocol==='https:';
if(!secure&&(process.env.NODE_ENV==='production'||!['127.0.0.1','localhost'].includes(new URL(origin).hostname)))throw new Error('HTTPS_PUBLIC_ORIGIN_REQUIRED');
const sessions=pool?createSessionRepository(pool):undefined;
const verifyIdentity=verifyBearer&&sessions?createBrowserIdentityVerifier(verifyBearer,sessions,origin):undefined;
const browserAuth=verifyProof&&sessions?{verifyProof,sessions,origin,secure}:undefined;
const settings=pool?createSettingsRepository(pool):undefined;
const app=createApp(pool?{verifyIdentity,browserAuth,acceptInvitation:createInvitationAcceptor(pool),listInvitations:createInvitationReader(pool),revokeInvitation:createInvitationRevoker(pool),createInvitation:createInvitationWriter(pool),readPermissions:createPermissionReader(pool),exportLearning:createLearningExporter(pool),readSettings:settings!.read,writeSettings:settings!.write,checkDatabase:async()=>{await pool.query('SELECT 1')},listAuthorizedProfiles:createProfileReader(pool),submitRecognition:createRecognitionSubmitter(createProfileReader(pool),createAttemptWriter(pool)),createFamily:createFamilyWriter(pool),deleteProfile:createProfileDeletionWriter(pool),readDeletion:createDeletionReader(pool),readProgress:createProgressReader(pool),createMember:createMemberWriter(pool)}:{});
app.listen(port,process.env.HOST??'127.0.0.1',()=>console.log('Local API ready on port '+port));
for(const signal of ['SIGINT','SIGTERM'] as const)process.on(signal,()=>app.close(()=>{void pool?.end();}));
